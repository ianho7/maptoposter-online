// 主翻译函数
export function translateLocationName(name: string): string {
  if (!name) return name;
  
  // 优先匹配城市
  if (cityTranslations[name]) return cityTranslations[name];
  
  // 匹配国家
  if (countryTranslations[name]) return countryTranslations[name];
  
  // 匹配州
  if (stateTranslations[name]) return stateTranslations[name];
  
  // 处理 "City, State, Country" 格式
  const parts = name.split(',').map(p => p.trim());
  if (parts.length > 1) {
    const translatedParts = parts.map(part => translateLocationName(part));
    return translatedParts.join(', ');
  }
  
  return name;
}